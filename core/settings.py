# Email Configuration
# If valid EMAIL_HOST_USER & EMAIL_HOST_PASSWORD are set in backend/.env, sends real emails via SMTP.
# Otherwise, falls back to Console EmailBackend (prints full formatted email to python manage.py terminal).
